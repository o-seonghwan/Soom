# 2. 위험도 데이터 검증
# =====================================================

def validate_risk(risk):
    """
    위험도 데이터를 내부 표준 형식으로 변환한다.

    score: 0~100
    radiusM: 미터 단위
    """

    score = float(risk["score"])
    radius = float(risk["radiusM"])
    lat = float(risk["lat"])
    lng = float(risk["lng"])

    if not 0 <= score <= 100:
        raise ValueError(
            "위험점수는 0~100 사이여야 합니다."
        )

    if radius <= 0:
        raise ValueError(
            "위험 반경은 0보다 커야 합니다."
        )

    if not (-90 <= lat <= 90):
        raise ValueError("위도 범위가 잘못되었습니다.")

    if not (-180 <= lng <= 180):
        raise ValueError("경도 범위가 잘못되었습니다.")

    return {
        "id": str(risk["id"]),
        "lat": lat,
        "lng": lng,
        "score": score,
        "radiusM": radius,
    }


